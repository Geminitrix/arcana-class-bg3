#!/usr/bin/perl
# ARC-0005: the mod's Khonsu helpers, one function per loose file, become ONE file -- ArcanaHelpers.khn -- the way the
# base game keeps dozens of functions in CommonConditions.khn. The Toolkit's crash happens while Khonsu opens a script
# file from disk during the AI (Anubis) load (FindScript -> FileManager::OpenFile -> double delete in the file cache);
# one file instead of nine means one disk open instead of nine. Function names do not change: no stat changes.
#   - functions other helpers call come first (IsCardSpell, IsArcanaSpell);
#   - each section starts with "-- ===== <Name> =====", so a later update replaces one section;
#   - each source file must define exactly one function, named as the file;
#   - the originals are moved (not deleted) to 90_ARCHIVE/93_Old_Versions/2026-10-12_ARC-0005_khn_merged/.
#   perl merge_khn.pl            # shows what it would do
#   perl merge_khn.pl --apply    # writes (game and Toolkit closed, [fechado])
use strict; use warnings;
use File::Basename qw(dirname basename);
use File::Copy qw(move);
use File::Path qw(make_path);
use Cwd qw(abs_path);
my $G = $ENV{BG3_DATA} // 'C:/Program Files (x86)/Steam/steamapps/common/Baldurs Gate 3/Data';
my $M = 'AspectClass_9d734fbd-cb67-95c0-e2c9-46f05fe2f8a7';
my $DIR = "$G/Mods/$M/Scripts/thoth/helpers";
my $OUT = "$DIR/ArcanaHelpers.khn";
my $ARCHIVE = abs_path(dirname(__FILE__) . '/../../../..') . '/90_ARCHIVE/93_Old_Versions/2026-10-12_ARC-0005_khn_merged';
my @FIRST = qw(IsCardSpell IsArcanaSpell);   # called by other helpers
my $apply = grep { $_ eq '--apply' } @ARGV;

opendir my $d, $DIR or die "$DIR: $!";
my @files = sort grep { /\.khn$/ && $_ ne 'ArcanaHelpers.khn' } readdir $d;
closedir $d;
die "nothing to merge (already merged?)\n" unless @files;
my (%body, @bad);
for my $f (@files) {
    (my $name = $f) =~ s/\.khn$//;
    open my $h, '<:raw', "$DIR/$f" or die "$f: $!"; local $/; my $s = <$h>; close $h;
    $s =~ s/\r\n/\n/g; $s =~ s/\n+\z/\n/;
    my @fn = $s =~ /^function\s+(\w+)\s*\(/mg;
    push @bad, "$f defines @fn" unless @fn == 1 && $fn[0] eq $name;
    $body{$name} = $s;
}
die "STOP: " . join('; ', @bad) . "\n" if @bad;
my @order = ((grep { $body{$_} } @FIRST), grep { my $n = $_; !grep { $_ eq $n } @FIRST } sort keys %body);
my $out = "-- Arcana's Khonsu helpers, all in one file (ARC-0005, 2026-10-12): one disk open while the Toolkit loads the AI,\n"
        . "-- instead of one per function. Each section is one function; the names are what Stats conditions call.\n"
        . "-- IsWeaveSurge is generated by gen_emotion_alchemy.pl (55/_wip/Resonant/44_IsWeaveSurge.khn): update its section from there.\n";
$out .= "\n-- ===== $_ =====\n$body{$_}" for @order;
$out =~ s/\n/\r\n/g;
printf "%s %s: %d functions (%s)\n", ($apply ? 'write   ' : 'would   '), basename($OUT), scalar @order, join(', ', @order);
print(($apply ? 'move    ' : 'would move ') . "$_ -> $ARCHIVE/\n") for @files;
exit 0 unless $apply;
open my $h, '>:raw', $OUT or die "$OUT: $!"; print $h $out; close $h;
make_path($ARCHIVE);
move("$DIR/$_", "$ARCHIVE/$_") or die "move $_: $!" for @files;
print "done\n";
