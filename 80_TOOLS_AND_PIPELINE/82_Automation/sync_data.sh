#!/usr/bin/env bash
# sync_data — copy the mod from the game's Data folder into 50_ENGINEERING/51_Mod_Source (ADR-0003).
#
#   bash 80_TOOLS_AND_PIPELINE/82_Automation/sync_data.sh          # copy, then report what changed
#   bash 80_TOOLS_AND_PIPELINE/82_Automation/sync_data.sh --check  # only report differences, copy nothing
#
# One-way: Data -> 51. The mod LIVES in Data; this script only READS it, so it is safe with the game and
# the Toolkit open. Never edit 51 by hand — the next sync overwrites it.
#
# Left out of the copy: nested .git folders, *.bak* files, git hook samples, and the compiled Story
# (goals.raw, story.div, story.div.osi, story_ac.dat — regenerated by the Story Editor and full of
# base-game code). Successor of the old tools/sync-mod.sh, which copied only the deck files.

set -euo pipefail

MOD="AspectClass_9d734fbd-cb67-95c0-e2c9-46f05fe2f8a7"
GAME="${BG3_DATA:-/c/Program Files (x86)/Steam/steamapps/common/Baldurs Gate 3/Data}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DEST="$ROOT/50_ENGINEERING/51_Mod_Source"
PARTS=("Mods/$MOD" "Public/$MOD" "Editor/Mods/$MOD" "Projects/$MOD")

[ -d "$GAME/Mods/$MOD" ] || { echo "mod not found in $GAME — set BG3_DATA" >&2; exit 1; }

prune() {  # remove what never belongs in the copy
    local d="$1"
    find "$d" -type d -name .git -prune -exec rm -rf {} +
    find "$d" -type f \( -name '*.bak*' -o -name '*.sample' \) -delete
    rm -f "$d"/Story/goals.raw "$d"/Story/story.div "$d"/Story/story.div.osi "$d"/Story/story_ac.dat
}

if [ "${1:-}" = "--check" ]; then
    tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
    for p in "${PARTS[@]}"; do
        [ -e "$GAME/$p" ] || continue
        mkdir -p "$tmp/$(dirname "$p")"; cp -r "$GAME/$p" "$tmp/$p"; prune "$tmp/$p"
    done
    if diff -rq "$tmp" "$DEST" --exclude=_INDEX.md --exclude=_AGENT.md --exclude=.gitkeep; then
        echo "51 matches Data"
    else
        echo "51 differs from Data (lines above) — run without --check to sync" >&2; exit 2
    fi
    exit 0
fi

for p in "${PARTS[@]}"; do
    [ -e "$GAME/$p" ] || { echo "  missing in Data: $p" >&2; continue; }
    rm -rf "$DEST/$p"
    mkdir -p "$DEST/$(dirname "$p")"
    cp -r "$GAME/$p" "$DEST/$p"
    prune "$DEST/$p"
done

files=$(find "$DEST" -type f -not -name '_INDEX.md' -not -name '_AGENT.md' -not -name .gitkeep | wc -l)
changed=$(git -C "$ROOT" status --porcelain -- "$DEST" | wc -l)
echo "51_Mod_Source synced: $files files, $changed path(s) changed since the last commit"
