#!/usr/bin/perl
# A test guide's markdown record from its JSON (61.02/<S>/GUIDE_ARC-####.json -> .md beside it). The interactive page
# (TEST_GUIDES.json lists the pending guides, one tab per subproject) reads the same JSON.
#   perl 80_TOOLS_AND_PIPELINE/82_Automation/gen_test_guide_md.pl 60_QA_AND_TESTING/61_Test_Plan/61.02_Test_Cases/<S>/GUIDE_ARC-####.json
use strict; use warnings;
use JSON::PP;
for my $f (@ARGV) {
    open my $h, '<:raw', $f or die "$f: $!"; my $g = JSON::PP->new->decode(do { local $/; <$h> }); close $h;
    (my $sub = $f) =~ s{.*61\.02_Test_Cases/([^/]+)/.*}{$1};
    my $o = "---\nid: 61.02/$sub/GUIDE_$g->{ticket}\nowner: QA Lead\nsource: GUIDE_$g->{ticket}.json (the interactive page reads the same file) -- generated by gen_test_guide_md.pl\n---\n\n"
          . "# Test guide -- $g->{ticket} · $g->{title}\n\nResults go on the interactive test page (pass / fail / notes); this file is the record.\n\n## Before you start\n\n"
          . join('', map { "- $_\n" } @{ $g->{before} });
    my $n = 0;
    for my $s (@{ $g->{sessions} }) {
        $o .= "\n## $s->{name}\n\n**Setup:** $s->{setup}\n";
        for my $t (@{ $s->{tests} }) {
            $n++;
            $o .= "\n### $t->{id} · $t->{title} ($t->{rule})" . (($t->{kind} // '') eq 'observe' ? ' -- observe' : '') . "\n\n"
                . "- **Steps:** $t->{steps}\n- **Expected:** $t->{expected}\n- **Fails if:** $t->{fails}\n"
                . ($t->{planb} ? "- **Plan B:** $t->{planb}\n" : '');
        }
    }
    $o .= "\n## Not here\n\n$g->{nothere}\n" if $g->{nothere};
    (my $md = $f) =~ s/\.json$/.md/;
    open my $w, '>:raw', $md or die "$md: $!"; print $w $o; close $w;
    print "$md: $n tests\n";
}
