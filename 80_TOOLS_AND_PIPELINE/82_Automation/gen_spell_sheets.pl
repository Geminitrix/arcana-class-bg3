#!/usr/bin/perl
# gen_spell_sheets — write the 23.02 spell sheets of a dossier from a table (00.08, Spell Designer).
#
#   perl 80_TOOLS_AND_PIPELINE/82_Automation/gen_spell_sheets.pl <Subclass> <rows.psv> <ticket> [game state line]
#
# rows.psv: one sheet per line, fields separated by " | ":
#   file | name | kind | game id(s) | level gained | cost / resource | design § | numbers (25 ids, comma-separated or —) | intent | rules in words
# Lines starting with # are ignored. Writes 23_Spell_Design/23.02_Spell_Sheets/<Subclass>/<file>.md and its _INDEX.md
# (overwrites them: the table is the Spell Designer's working source for a regeneration). Run from the repository root.
use strict; use warnings; use utf8; use File::Path qw(make_path);
utf8::decode($_) for @ARGV;   # arguments arrive as UTF-8 bytes
my ($S, $rows, $ticket, $state) = @ARGV;
die "usage: gen_spell_sheets.pl <Subclass> <rows.psv> <ticket> [game state line]\n" unless $S && $rows && $ticket;
$state //= 'built';
my $D = "20_GAME_DESIGN/23_Spell_Design/23.02_Spell_Sheets/$S"; make_path($D);
open my $in, '<:encoding(UTF-8)', $rows or die "$rows: $!";
my @rows = map { [split /\s*\|\s*/] } grep { /\S/ && !/^#/ } map { s/[\r\n]+$//r } <$in>;
my @t = localtime; my $date = sprintf '%04d-%02d-%02d', $t[5]+1900, $t[4]+1, $t[3];
for (@rows) {
  my ($f, $name, $kind, $id, $lvl, $cost, $sec, $num, $intent, $rules) = @$_;
  die "row '$f' has " . scalar(@$_) . " fields, expected 10\n" unless @$_ == 10;
  my $numbers = $num eq '—' ? '—' : join(', ', map { my $d = /^SPL/ ? '25.01_spells' : /^FEAT/ ? '25.02_features' : '25.03_statuses'; "`$d/$_.yaml`" } split /,\s*/, $num);
  open my $o, '>:encoding(UTF-8)', "$D/$f.md" or die $!;
  print $o "---\nid: 23.02/$S/$f\nowner: Spell Designer\ngame_id: $id\ndesign: 21.04/$S/DESIGN.md $sec\nreviewed: $date $ticket — generated by gen_spell_sheets.pl (propagation, 00.08)\n---\n\n"
         . "# $name — $kind\n\n**Intent:** $intent\n\n**Rules in words:** $rules\n\n"
         . "| | |\n|---|---|\n| Gained at | level $lvl |\n| Cost / resource | $cost |\n| Numbers | $numbers |\n| In game | $state |\n";
  close $o;
}
open my $i, '>:encoding(UTF-8)', "$D/_INDEX.md" or die;
print $i "# 23.02 · Spell sheets — The $S\n\nOne sheet per card, passive and status family (00.08). Design: `21.04/$S/DESIGN.md`; numbers: `25`.\n\n| Sheet | Name | Kind | Level |\n|---|---|---|---|\n";
print $i "| [$_->[0]]($_->[0].md) | $_->[1] | $_->[2] | $_->[4] |\n" for @rows;
close $i;
print "sheets: " . scalar(@rows) . " in $D\n";
