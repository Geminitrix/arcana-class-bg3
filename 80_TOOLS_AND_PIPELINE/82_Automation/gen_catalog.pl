#!/usr/bin/perl
# gen_catalog — build the Live Context catalogues (05.03, 05.04) and the read-only master-data inventory
# (25.05_inventory, ADR-0005) from the synchronized copy of the mod in 51. Run after sync_data.
#
#   perl 80_TOOLS_AND_PIPELINE/82_Automation/gen_catalog.pl            (from the repository root)
#
# Reads only 51; writes only 05.03, 05.04 and 25.05. Handles are resolved against the English loca.
# Upcast variants (<card>_N whose base entry exists) are counted, not listed.
use strict; use warnings; use utf8;
use File::Path qw(make_path);
binmode STDOUT, ':utf8';

my $MOD   = 'AspectClass_9d734fbd-cb67-95c0-e2c9-46f05fe2f8a7';
my $SRC   = "50_ENGINEERING/51_Mod_Source";
my $STATS = "$SRC/Public/$MOD/Stats/Generated/Data";
my $LOCA  = "$SRC/Mods/$MOD/Localization/English/english.xml";
my $O3    = "05_LIVE_CONTEXT/05.03_Spells_and_Passives";
my $O4    = "05_LIVE_CONTEXT/05.04_Statuses_and_Conditions";
my $O25   = "20_GAME_DESIGN/25_Master_Data/25.05_inventory";
-d $STATS or die "run from the repository root after sync_data ($STATS not found)\n";

my $commit = `git rev-parse --short HEAD`; chomp $commit;
my @t = localtime; my $date = sprintf '%04d-%02d-%02d', $t[5]+1900, $t[4]+1, $t[3];

# --- loca ---
my %loca;
if (open my $fh, '<:encoding(UTF-8)', $LOCA) {
  while (<$fh>) {
    next unless /contentuid="([^"]+)"[^>]*>(.*?)<\/content>/;
    my ($k, $v) = ($1, $2);
    $v =~ s/&lt;[^&]*?&gt;//g; $v =~ s/&quot;/"/g; $v =~ s/&amp;/&/g; $v =~ s/&apos;/'/g;
    $loca{$k} = $v;
  }
}
sub name_of { my $h = shift // ''; $h =~ s/;\d+$//; my $n = $loca{$h} // ''; $n =~ s/\|/\\|/g; $n }

# --- stats ---
my (%e, @order);
for my $file (sort glob "$STATS/*.txt") {
  (my $base = $file) =~ s{.*/}{}; $base =~ s/\.txt$//;
  open my $fh, '<:encoding(UTF-8)', $file or die "$file: $!";
  my $cur;
  while (my $l = <$fh>) {
    $l =~ s/[\r\n]+$//;
    if ($l =~ /^new entry "([^"]+)"/) { $cur = $1; push @order, $cur; $e{$cur} = { file => $base, data => [] }; next }
    next unless defined $cur;
    if    ($l =~ /^type "([^"]+)"/)  { $e{$cur}{type}  = $1 }
    elsif ($l =~ /^using "([^"]+)"/) { $e{$cur}{using} = $1 }
    elsif ($l =~ /^data "([^"]+)" "(.*)"$/) { push @{ $e{$cur}{data} }, [$1, $2] }
  }
}
sub field { my ($n, $f, $d) = @_; $d //= 0; return '' if $d > 10 || !$e{$n};
  for (@{ $e{$n}{data} }) { return $_->[1] if $_->[0] eq $f }
  return $e{$n}{using} ? field($e{$n}{using}, $f, $d+1) : '' }
sub is_variant { my $n = shift; $n =~ /^(.+)_\d+$/ && exists $e{$1} }

my $hdr = sub { my $src = shift;
  "---\nsource: $src (generated by 82_Automation/gen_catalog.pl)\nsynced_at: $date ($commit)\nstate: synced\n---\n\n" };

sub w { my ($p, $t) = @_; (my $d = $p) =~ s{/[^/]+$}{}; make_path($d);
  open my $f, '>:encoding(UTF-8)', $p or die "$p: $!"; print $f $t; close $f; unlink "$d/.gitkeep" }

# --- 05.03 spells ---
my (@sp, %var);
for my $n (@order) {
  next unless ($e{$n}{type} // '') eq 'SpellData';
  if (is_variant($n)) { (my $b = $n) =~ s/_\d+$//; $var{$b}++; next }
  push @sp, $n;
}
my $t = $hdr->('51 Public Stats Spell_*.txt + English loca') . "# 05.03 · Spell catalogue\n\n"
      . scalar(@sp) . " spells (upcast variants counted in the last column). Internal name = Stats entry.\n\n"
      . "| Internal name | Type | Level | In-game name | Upcasts |\n|---|---|---|---|---|\n";
$t .= sprintf "| `%s` | %s | %s | %s | %s |\n", $_, field($_,'SpellType'), field($_,'Level') || '0',
        name_of(field($_,'DisplayName')), $var{$_} // '' for @sp;
w("$O3/Spell_Catalog.md", $t);

# --- 05.03 passives ---
my @pa = grep { ($e{$_}{type} // '') eq 'PassiveData' } @order;
$t = $hdr->('51 Public Stats Passive.txt + English loca') . "# 05.03 · Passive catalogue\n\n"
   . scalar(@pa) . " passives.\n\n| Internal name | In-game name |\n|---|---|\n";
$t .= sprintf "| `%s` | %s |\n", $_, name_of(field($_,'DisplayName')) for @pa;
w("$O3/Passive_Catalog.md", $t);

# --- 05.04 statuses ---
my @st = grep { ($e{$_}{type} // '') eq 'StatusData' } @order;
$t = $hdr->('51 Public Stats Status_*.txt + English loca') . "# 05.04 · Status catalogue\n\n"
   . scalar(@st) . " statuses. *Tech* = hidden helper (`_TECH`, `_TECHNICAL`, `_HELPER`).\n\n"
   . "| Internal name | Status type | In-game name | Tech |\n|---|---|---|---|\n";
$t .= sprintf "| `%s` | %s | %s | %s |\n", $_, field($_,'StatusType'), name_of(field($_,'DisplayName')),
        ($_ =~ /_(TECH|TECHNICAL|HELPER)$/ ? 'yes' : '') for @st;
w("$O4/Status_Catalog.md", $t);

# --- 25.05 inventory (YAML, one file per Stats file) ---
my %byfile; push @{ $byfile{$e{$_}{file}} }, $_ for @order;
for my $file (sort keys %byfile) {
  my $y = "# GENERATED by 82_Automation/gen_catalog.pl from 51 — read-only (ADR-0005). Do not edit.\n"
        . "# synced_at: $date ($commit)\n";
  for my $n (@{ $byfile{$file} }) {
    $y .= "\"$n\":\n  type: \"" . ($e{$n}{type} // '') . "\"\n";
    $y .= "  using: \"$e{$n}{using}\"\n" if $e{$n}{using};
    for (@{ $e{$n}{data} }) { (my $v = $_->[1]) =~ s/\\/\\\\/g; $v =~ s/"/\\"/g; $y .= "  $_->[0]: \"$v\"\n" }
  }
  w("$O25/$file.yaml", $y);
}
printf "spells %d (+%d variants), passives %d, statuses %d, inventory files %d\n",
  scalar @sp, (eval { my $s = 0; $s += $_ for values %var; $s }), scalar @pa, scalar @st, scalar keys %byfile;
